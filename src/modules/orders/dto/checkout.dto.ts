import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsEnum, IsOptional, IsString, IsUUID, MaxLength } from 'class-validator';

export enum PaymentMethodDto {
  COD = 'COD',
  /** Offered only for shops that have configured their own SePay account (ADR-014).
   *  The checkout preview says which methods a given shop actually accepts. */
  SEPAY_QR = 'SEPAY_QR',
}

export class CheckoutPreviewDto {
  @ApiProperty({ format: 'uuid', description: 'The cart group being checked out' })
  @IsUUID()
  shopId!: string;

  @ApiPropertyOptional({ format: 'uuid', description: 'Defaults to the default address' })
  @IsOptional()
  @IsUUID()
  addressId?: string;
}

export class PlaceOrderDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  shopId!: string;

  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  addressId!: string;

  @ApiProperty({ enum: PaymentMethodDto, default: PaymentMethodDto.COD })
  @IsEnum(PaymentMethodDto)
  paymentMethod!: PaymentMethodDto;

  @ApiPropertyOptional({ maxLength: 500, description: 'Buyer message to the shop' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  note?: string;

  @ApiProperty({
    format: 'uuid',
    description:
      'Generated by the client once per checkout attempt. Resubmitting the same key returns the order already placed instead of placing a second one.',
  })
  @IsUUID()
  idempotencyKey!: string;
}

export class CancelOrderDto {
  @ApiPropertyOptional({ maxLength: 200 })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  reason?: string;
}
